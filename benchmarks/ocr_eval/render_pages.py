"""
Rendered test images: each problem typeset exactly as on the photo sheet
(make_sheets.py: KaTeX math, Times text) and screenshotted by headless Chrome.

    .venv/bin/python benchmarks/ocr_eval/render_pages.py              # blur radius 2.0
    .venv/bin/python benchmarks/ocr_eval/render_pages.py --blur 3

Writes, per problem:
    dataset/photos/rendered/<id>.png        sharp, like a screenshot
    dataset/photos/rendered_blur/<id>.png   the same image, Gaussian-blurred

These are typeset from the problem text, NOT generated by an AI image model,
so every character in the image is known exactly. Like Research Update #2's
"computer-made (blurry)" images, report them separately from real photos.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter

from dataset import load_problems
from make_sheets import sheet_html

ROOT = Path(__file__).resolve().parents[2]
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
W, H = 1600, 1000


def screenshot(html_path: Path, png: Path) -> None:
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    f"--window-size={W},{H}", "--virtual-time-budget=6000",
                    f"--screenshot={png}", html_path.as_uri()],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def check_fits(im: Image.Image) -> bool:
    """Text must not touch the left/right edge (a long equation cut off by the window)."""
    bbox = ImageChops.invert(im.convert("L")).getbbox()
    return bbox is not None and bbox[0] > 20 and bbox[2] < W - 20


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", type=Path, default=ROOT / "dataset")
    ap.add_argument("--blur", type=float, default=2.0, help="Gaussian blur radius in pixels")
    a = ap.parse_args()
    if not Path(CHROME).exists():
        sys.exit("needs Google Chrome in /Applications")

    sharp, blur = a.dataset / "photos" / "rendered", a.dataset / "photos" / "rendered_blur"
    sharp.mkdir(parents=True, exist_ok=True)
    blur.mkdir(parents=True, exist_ok=True)
    bad = []
    with tempfile.TemporaryDirectory() as tmp:
        for p in load_problems(a.dataset).values():
            page = Path(tmp) / f"{p.problem_id}.html"
            page.write_text(sheet_html([p]), encoding="utf-8")
            out = sharp / f"{p.problem_id}.png"
            screenshot(page, out)
            im = Image.open(out).convert("RGB")
            if not check_fits(im):
                bad.append(p.problem_id)
            im.filter(ImageFilter.GaussianBlur(a.blur)).save(blur / f"{p.problem_id}.png")
            print("rendered", p.problem_id)
    if bad:
        print("WARNING: text touches the image edge (may be cut off):", ", ".join(bad))
    print(f"-> {sharp}\n-> {blur}")


if __name__ == "__main__":
    main()
